export function createContactScene3D(canvas: HTMLCanvasElement, opts: Opts = {}): ContactScene | null {
  let renderer: THREE.WebGLRenderer;
  try {
    renderer = new THREE.WebGLRenderer({ canvas, antialias: false, alpha: false, powerPreference: 'high-performance' });
  } catch {
    return null;
  }
  const lowPower = !!opts.lowPower;
  const reduceStill = !!opts.reduceMotion;
  const MAX_DPR = lowPower ? 1.15 : 1.5;
  let quality = lowPower ? 0.85 : 1;
  let W = 2, H = 2, aspect = 1;
  let mobile = false;
  let pan = 0;
  let scrollPx = 0;
  let ready = false, destroyed = false, running = false, raf = 0, lastT = 0, slow = 0;
  const t0 = performance.now();

  renderer.outputColorSpace = THREE.SRGBColorSpace;
  renderer.toneMapping = THREE.NoToneMapping; // the lake shader and the OutputPass do their own mapping
  renderer.autoClear = false;
  renderer.setClearColor(0x120a24, 1);

  /* ---------- backdrop: the lake shader ---------- */
  const bgScene = new THREE.Scene();
  const bgCam = new THREE.OrthographicCamera(-1, 1, 1, -1, 0, 1);
  const lakeFrag = FRAG_LAKE.replace('gl_FragColor = vec4(col, 1.0);', 'col = pow(max(col, 0.0), vec3(2.2));\n  gl_FragColor = vec4(col, 1.0);\n  #include <colorspace_fragment>');
  const lakeMat = new THREE.ShaderMaterial({
    vertexShader: 'void main(){ gl_Position = vec4(position.xy, 0.0, 1.0); }',
    fragmentShader: lakeFrag,
    uniforms: {
      uRes: { value: new THREE.Vector2(2, 2) },
      uTime: { value: 0 },
      uCam: { value: 0 },
      uHz: { value: 0.56 },
      uMoonX: { value: 0.4 },
      uMoonY: { value: 0.215 },
      uLow: { value: lowPower ? 1 : 0 },
    },
    depthTest: false,
    depthWrite: false,
  });
  bgScene.add(new THREE.Mesh(new THREE.PlaneGeometry(2, 2), lakeMat));

  /* ---------- the garden ---------- */
  const scene = new THREE.Scene();
  scene.fog = new THREE.Fog(0x3a2468, 14, 46);
  const camera = new THREE.PerspectiveCamera(34, 1, 0.1, 120);

  const GX = 26; // where the garden stands along the shore (the lake is at x = 0)
  const garden = new THREE.Group();
  garden.position.set(GX, 0, 0);
  scene.add(garden);

  /* lights: moonlight from the upper left, a hemisphere of lilac sky, and a glow that comes from inside the canopy */
  const moonLight = new THREE.DirectionalLight(0xd3c2ff, 2.6);
  moonLight.position.set(GX - 7, 11, 6);
  moonLight.target.position.set(GX, 2, 0);
  scene.add(moonLight, moonLight.target);
  scene.add(new THREE.HemisphereLight(0x8a63e6, 0x1b0f3d, 1.05));
  const canopyGlow = new THREE.PointLight(0xb38dff, 16, 14, 2);
  canopyGlow.position.set(GX - 0.5, 3.0, 3.2);
  scene.add(canopyGlow);
  const chairGlow = new THREE.PointLight(0xc9a8ff, 10, 7, 2);
  chairGlow.position.set(GX + 0.2, 1.6, 2.4);
  scene.add(chairGlow);

  const R = rng(5);

  /* ----- bark: dark violet, grooved, with a faint cool rim ----- */
  const barkNormal = normalFromNoise(256, 5, 9, 0.18);
  barkNormal.repeat.set(2, 3);
  const barkMat = new THREE.MeshStandardMaterial({ color: 0x3a2466, roughness: 0.92, metalness: 0, normalMap: barkNormal, normalScale: new THREE.Vector2(1.6, 1.6) });

  /* ----- the tree: trunk + recursive branches, then leaf cards around the twig ends ----- */
  const branchGeos: THREE.BufferGeometry[] = [];
  const anchors: { p: THREE.Vector3; w: number }[] = [];
  const CANOPY_C = new THREE.Vector3(0.2, 5.2, 0);

  const grow = (start: THREE.Vector3, dir: THREE.Vector3, len: number, rad: number, depth: number) => {
    const pts = [start.clone()];
    const p = start.clone();
    const d = dir.clone().normalize();
    const segs = depth === 0 ? 5 : 4;
    for (let i = 1; i <= segs; i++) {
      d.add(new THREE.Vector3((R() - 0.5) * 0.55, (R() - 0.5) * 0.35 + 0.04, (R() - 0.5) * 0.55)).normalize();
      p.addScaledVector(d, len / segs);
      pts.push(p.clone());
    }
    branchGeos.push(taperedTube(pts, (t) => Math.max(0.018, rad * (1 - t * 0.82)), depth > 1 ? 7 : 10, 1.4));
    if (depth > 0) {
      const kids = depth === 3 ? 4 : depth === 2 ? 3 : 3;
      for (let k = 0; k < kids; k++) {
        const t = 0.35 + (k / kids) * 0.6;
        const idx = Math.min(pts.length - 1, Math.floor(t * pts.length));
        const base = pts[idx];
        const side = new THREE.Vector3(R() - 0.5, R() * 0.5 - 0.1, R() - 0.5).normalize();
        const nd = d.clone().multiplyScalar(0.5).add(side.multiplyScalar(0.9)).normalize();
        if (nd.y < -0.15) nd.y = -0.15;
        grow(base, nd, len * (0.62 + R() * 0.12), rad * 0.5, depth - 1);
      }
      anchors.push({ p: pts[pts.length - 1].clone(), w: 0.7 });
    } else {
      anchors.push({ p: p.clone(), w: 1 });
      anchors.push({ p: pts[Math.floor(pts.length * 0.6)].clone(), w: 0.6 });
    }
  };

  /* trunk: slightly leaning, flared at the foot */
  {
    const pts = [new THREE.Vector3(0, -0.3, 0), new THREE.Vector3(0.05, 1.4, 0.05), new THREE.Vector3(-0.08, 3.0, 0), new THREE.Vector3(0.1, 4.4, -0.05)];
    branchGeos.push(
      taperedTube(
        pts,
        (t) => 0.98 * (1 - t * 0.5) + 0.6 * Math.pow(Math.max(0, 1 - t * 5.5), 2),
        14,
        1.1,
      ),
    );
    const top = new THREE.Vector3(0.1, 4.2, -0.05);
    grow(top, new THREE.Vector3(-0.9, 0.9, 0.2), 4.2, 0.36, 3);
    grow(top, new THREE.Vector3(1.0, 0.8, 0.0), 4.4, 0.36, 3);
    grow(top, new THREE.Vector3(0.1, 1.0, -0.8), 4.0, 0.32, 3);
    grow(new THREE.Vector3(0, 3.6, 0), new THREE.Vector3(-0.6, 0.6, 0.9), 3.2, 0.28, 3);
    grow(new THREE.Vector3(0, 3.4, 0), new THREE.Vector3(0.7, 0.55, 0.8), 3.4, 0.28, 3);
    grow(top, new THREE.Vector3(-0.2, 1.0, 0.9), 3.2, 0.26, 3);
  }
  const bark = new THREE.Mesh(mergeGeometries(branchGeos, false)!, barkMat);
  garden.add(bark);

  /* ----- leaves: instanced cards with a leaf-shaped alpha texture, coloured by how much moonlight they catch ----- */
  const leafTex = canvasTex(128, 128, (g) => {
    g.clearRect(0, 0, 128, 128);
    const grd = g.createLinearGradient(0, 0, 0, 128);
    grd.addColorStop(0, '#ffffff');
    grd.addColorStop(1, '#d9ccff');
    g.fillStyle = grd;
    g.beginPath();
    g.moveTo(64, 4);
    g.bezierCurveTo(112, 30, 110, 92, 64, 124);
    g.bezierCurveTo(18, 92, 16, 30, 64, 4);
    g.fill();
    g.strokeStyle = 'rgba(80,50,150,0.55)'; // midrib + veins
    g.lineWidth = 3;
    g.beginPath();
    g.moveTo(64, 8);
    g.lineTo(64, 122);
    g.stroke();
    g.lineWidth = 1.6;
    for (let i = 0; i < 6; i++) {
      const y = 28 + i * 15;
      g.beginPath();
      g.moveTo(64, y);
      g.lineTo(100 - i * 3, y - 14);
      g.moveTo(64, y);
      g.lineTo(28 + i * 3, y - 14);
      g.stroke();
    }
  });
  const LEAF_COUNT = lowPower ? 9000 : 24000;
  const leafGeo = new THREE.PlaneGeometry(0.34, 0.40);
  leafGeo.translate(0, 0.3, 0);
  const leafMat = new THREE.MeshStandardMaterial({
    map: leafTex,
    alphaTest: 0.5,
    side: THREE.DoubleSide,
    roughness: 0.55,
    metalness: 0,
    emissive: new THREE.Color(0x2c1670),
    emissiveIntensity: 0.3,
  });
  const leaves = new THREE.InstancedMesh(leafGeo, leafMat, LEAF_COUNT);
  {
    const m = new THREE.Matrix4(), q = new THREE.Quaternion(), e = new THREE.Euler(), sc = new THREE.Vector3(), p = new THREE.Vector3();
    const col = new THREE.Color();
    const toMoon = new THREE.Vector3(-0.55, 0.75, 0.4).normalize();
    const ramp = ['#1f0f55', '#33198a', '#5d3cc4', '#8e66ec', '#c79cff', '#efc6ff', '#fff0fb'].map((c) => new THREE.Color(c));
    const pick = (t: number) => {
      const f = Math.max(0, Math.min(0.999, t)) * (ramp.length - 1);
      const i = Math.floor(f);
      return ramp[i].clone().lerp(ramp[i + 1], f - i);
    };
    const totalW = anchors.reduce((a, b) => a + b.w, 0);
    for (let i = 0; i < LEAF_COUNT; i++) {
      let r = R() * totalW;
      let an = anchors[0];
      for (const a of anchors) {
        r -= a.w;
        if (r <= 0) {
          an = a;
          break;
        }
      }
      const spread = 0.7 + R() * 1.5;
      p.set(an.p.x + (R() - 0.5) * 2 * spread, an.p.y + (R() - 0.5) * 1.5 * spread, an.p.z + (R() - 0.5) * 2 * spread);
      const out = p.clone().sub(CANOPY_C).normalize();
      const lit = out.dot(toMoon) * 0.5 + 0.5;
      e.set((R() - 0.5) * 1.6 - out.y * 0.5, R() * Math.PI * 2, (R() - 0.5) * 1.4);
      q.setFromEuler(e);
      sc.setScalar(0.5 + R() * 0.7);
      m.compose(p, q, sc);
      leaves.setMatrixAt(i, m);
      const t = Math.pow(lit, 1.5) * 1.05 + (R() - 0.5) * 0.45 + (p.y > 5.2 ? 0.08 : 0) - (p.distanceTo(CANOPY_C) > 4.4 ? 0.1 : 0);
      col.copy(pick(t));
      leaves.setColorAt(i, col);
    }
    leaves.instanceMatrix.needsUpdate = true;
    if (leaves.instanceColor) leaves.instanceColor.needsUpdate = true;
  }
  garden.add(leaves);

  /* ----- ground: a meadow that falls away toward the lake ----- */
  const groundGeo = new THREE.PlaneGeometry(64, 44, 96, 64);
  groundGeo.rotateX(-Math.PI / 2);
  {
    const pa = groundGeo.attributes.position as THREE.BufferAttribute;
    const colors: number[] = [];
    for (let i = 0; i < pa.count; i++) {
      const x = pa.getX(i), z = pa.getZ(i);
      const bank = Math.max(0, (-x - 8) / 8); // toward the lake (to the left) the meadow drops
      const y = (fbm3(x * 0.18, 0, z * 0.18) - 0.35) * 0.9 - bank * bank * 4.5;
      pa.setY(i, y);
      const t = smooth(-6, 8, z);
      colors.push(lerp(0.16, 0.10, t), lerp(0.10, 0.06, t), lerp(0.36, 0.22, t));
    }
    groundGeo.setAttribute('color', new THREE.Float32BufferAttribute(colors, 3));
    groundGeo.computeVertexNormals();
  }
  garden.add(new THREE.Mesh(groundGeo, new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 1, metalness: 0 })));

  /* ----- grass: thousands of curved blades that sway ----- */
  const grassUniforms = { uTime: { value: 0 } };
  const bladeGeo = (() => {
    const segs = 5, pos: number[] = [], uv: number[] = [], col: number[] = [], idx: number[] = [];
    for (let i = 0; i <= segs; i++) {
      const t = i / segs;
      const w = 0.026 * (1 - t * 0.92);
      const bend = t * t * 0.25;
      pos.push(-w, t, bend, w, t, bend);
      uv.push(0, t, 1, t);
      const c = new THREE.Color().lerpColors(new THREE.Color('#07031a'), new THREE.Color('#5d41b4'), Math.pow(t, 1.6));
      col.push(c.r, c.g, c.b, c.r, c.g, c.b);
      if (i < segs) {
        const a = i * 2;
        idx.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
      }
    }
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
    g.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
    g.setAttribute('color', new THREE.Float32BufferAttribute(col, 3));
    g.setIndex(idx);
    g.computeVertexNormals();
    return g;
  })();
  const grassMat = new THREE.MeshStandardMaterial({ vertexColors: true, side: THREE.DoubleSide, roughness: 0.85, emissive: new THREE.Color(0x140838), emissiveIntensity: 0.28 });
  grassMat.onBeforeCompile = (sh) => {
    sh.uniforms.uTime = grassUniforms.uTime;
    sh.vertexShader = sh.vertexShader
      .replace('#include <common>', '#include <common>\nuniform float uTime;')
      .replace(
        '#include <begin_vertex>',
        `#include <begin_vertex>
         float h = uv.y;
         vec4 ip = instanceMatrix * vec4(0.0, 0.0, 0.0, 1.0);
         transformed.x += sin(uTime * 1.35 + ip.x * 0.55 + ip.z * 0.35) * 0.16 * h * h;
         transformed.z += cos(uTime * 1.05 + ip.x * 0.35 + ip.z * 0.6) * 0.09 * h * h;`,
      );
  };
  const GRASS = lowPower ? 12000 : 42000;
  const grass = new THREE.InstancedMesh(bladeGeo, grassMat, GRASS);
  const clearPatches: [number, number, number][] = []; // chair spots keep the grass short
  {
    const m = new THREE.Matrix4(), q = new THREE.Quaternion(), e = new THREE.Euler(), sc = new THREE.Vector3(), p = new THREE.Vector3();
    const col = new THREE.Color();
    const rg = rng(77);
    const patches = [[-0.95, 2.9, 2.0], [1.05, 3.3, 2.1]];
    for (let i = 0; i < GRASS; i++) {
      const x = (rg() - 0.5) * 22 + (rg() - 0.5) * 6;
      const z = -7 + Math.pow(rg(), 0.7) * 17;
      let h = 0.16 + rg() * 0.34;
      for (const [px, pz, pr] of patches) {
        const d = Math.hypot(x - px, z - pz);
        if (d < pr) h *= 0.12 + 0.88 * Math.pow(d / pr, 1.5);
      }
      const yG = (fbm3((x + GX) * 0.18 - GX * 0.18, 0, z * 0.18) - 0.35) * 0.9 - 0.02;
      p.set(x, yG, z);
      e.set((rg() - 0.5) * 0.35, rg() * Math.PI * 2, (rg() - 0.5) * 0.35);
      q.setFromEuler(e);
      sc.set(0.8 + rg() * 0.8, h, 1);
      m.compose(p, q, sc);
      grass.setMatrixAt(i, m);
      col.setHSL(0.74 + (rg() - 0.5) * 0.04, 0.30 + rg() * 0.15, 0.42 + (rg() - 0.5) * 0.2);
      grass.setColorAt(i, col);
    }
    void clearPatches;
    grass.instanceMatrix.needsUpdate = true;
    if (grass.instanceColor) grass.instanceColor.needsUpdate = true;
  }
  grass.frustumCulled = false;
  garden.add(grass);

  /* ----- standing stones behind the tree ----- */
  const rockGroup = new THREE.Group();
  const rockMat = new THREE.MeshStandardMaterial({ color: 0x241545, roughness: 0.95, metalness: 0 });
  const makeRock = (seed: number, w: number, h: number) => {
    const g = new THREE.IcosahedronGeometry(1, 5);
    const pa = g.attributes.position as THREE.BufferAttribute;
    const v = new THREE.Vector3();
    for (let i = 0; i < pa.count; i++) {
      v.fromBufferAttribute(pa, i);
      const n = fbm3(v.x * 1.6 + seed, v.y * 1.6, v.z * 1.6 + seed * 0.7);
      const d = 1 + (n - 0.4) * 0.55;
      v.multiplyScalar(d);
      v.x *= w;
      v.z *= w * 0.8;
      v.y = v.y < -0.35 ? -0.35 : v.y;
      v.y *= h;
      pa.setXYZ(i, v.x, v.y, v.z);
    }
    g.computeVertexNormals();
    return new THREE.Mesh(g, rockMat);
  };
  [
    [-7.5, -9, 1.5, 2.6], [-3.8, -12, 1.1, 2.0], [4.5, -10, 1.3, 2.4], [8.5, -8, 1.7, 3.0], [-10.5, -6, 1.2, 2.1], [11.5, -11, 1.4, 2.5], [1.0, -14, 1.0, 1.8],
  ].forEach(([x, z, w, h], i) => {
    const r = makeRock(i * 3.1, w, h);
    r.position.set(x, h * 0.35, z);
    r.rotation.y = i * 1.3;
    rockGroup.add(r);
  });
  garden.add(rockGroup);

  /* ----- chairs ----- */
  const woodTex = canvasTex(256, 256, (g) => {
    g.fillStyle = '#6e3a46';
    g.fillRect(0, 0, 256, 256);
    const rw = rng(9);
    for (let i = 0; i < 90; i++) {
      g.strokeStyle = `rgba(${40 + rw() * 40},${15 + rw() * 15},${25 + rw() * 20},${0.12 + rw() * 0.25})`;
      g.lineWidth = 1 + rw() * 3;
      g.beginPath();
      g.moveTo(rw() * 256, 0);
      g.bezierCurveTo(rw() * 256, 80, rw() * 256, 160, rw() * 256, 256);
      g.stroke();
    }
  }, true, true);
  const woodMat = new THREE.MeshStandardMaterial({ map: woodTex, roughness: 0.5, metalness: 0.02, color: 0xc9a0a8 });
  const fabricNormal = normalFromNoise(128, 38, 5);
  fabricNormal.repeat.set(2, 2);
  const makeFabric = (hex: number) =>
    new THREE.MeshPhysicalMaterial({ color: hex, roughness: 0.92, metalness: 0, sheen: 0.8, sheenColor: new THREE.Color(0xd9c6ff), sheenRoughness: 0.6, normalMap: fabricNormal, normalScale: new THREE.Vector2(0.35, 0.35), emissive: new THREE.Color(0x1d0e55), emissiveIntensity: 0.12 });

  const makeChair = (fabricHex: number) => {
    const c = new THREE.Group();
    const fabric = makeFabric(fabricHex);
    const rbox = (w: number, h: number, d: number, r: number, mat: THREE.Material) => new THREE.Mesh(new RoundedBoxGeometry(w, h, d, 4, r), mat);
    for (const s of [-1, 1]) {
      const frontLeg = rbox(0.05, 0.42, 0.05, 0.012, woodMat);
      frontLeg.position.set(s * 0.36, 0.21, 0.27);
      frontLeg.rotation.z = -s * 0.05;
      const rearLeg = rbox(0.05, 0.5, 0.05, 0.012, woodMat);
      rearLeg.position.set(s * 0.37, 0.25, -0.3);
      rearLeg.rotation.x = 0.22;
      const post = rbox(0.045, 0.7, 0.045, 0.012, woodMat); // back post rising behind the cushion
      post.position.set(s * 0.37, 0.64, -0.36);
      post.rotation.x = -0.26;
      const arm = rbox(0.07, 0.04, 0.7, 0.015, woodMat);
      arm.position.set(s * 0.38, 0.62, -0.02);
      const armSupport = rbox(0.045, 0.24, 0.045, 0.012, woodMat);
      armSupport.position.set(s * 0.38, 0.5, 0.28);
      const sideRail = rbox(0.04, 0.06, 0.66, 0.012, woodMat);
      sideRail.position.set(s * 0.37, 0.34, -0.02);
      c.add(frontLeg, rearLeg, post, arm, armSupport, sideRail);
    }
    const frontRail = rbox(0.74, 0.05, 0.04, 0.012, woodMat);
    frontRail.position.set(0, 0.34, 0.27);
    const backRail = rbox(0.74, 0.05, 0.04, 0.012, woodMat);
    backRail.position.set(0, 0.34, -0.3);
    const seat = rbox(0.7, 0.13, 0.64, 0.05, fabric);
    seat.position.set(0, 0.44, 0.0);
    seat.rotation.x = -0.03;
    const back = rbox(0.68, 0.64, 0.13, 0.055, fabric);
    back.position.set(0, 0.76, -0.31);
    back.rotation.x = -0.25;
    c.add(frontRail, backRail, seat, back);
    return c;
  };
  const chairs = new THREE.Group();
  const chairA = makeChair(0x7d5fe0);
  chairA.scale.setScalar(1.4);
  chairA.position.set(-0.95, 0.0, 2.9);
  chairA.rotation.y = 0.72;
  const chairB = makeChair(0x8a6cf0);
  chairB.scale.setScalar(1.4);
  chairB.position.set(1.05, 0.0, 3.3);
  chairB.rotation.y = -0.78;
  chairs.add(chairA, chairB);
  garden.add(chairs);

  /* soft dark pools under the chairs and the tree (cheap fake shadows) */
  const shadowTex = canvasTex(128, 128, (g) => {
    const gr = g.createRadialGradient(64, 64, 4, 64, 64, 62);
    gr.addColorStop(0, 'rgba(4,1,14,0.8)');
    gr.addColorStop(1, 'rgba(4,1,14,0)');
    g.fillStyle = gr;
    g.fillRect(0, 0, 128, 128);
  }, true);
  const shadowMat = new THREE.MeshBasicMaterial({ map: shadowTex, transparent: true, depthWrite: false });
  const blob = (x: number, z: number, sx: number, sz: number) => {
    const m = new THREE.Mesh(new THREE.PlaneGeometry(1, 1), shadowMat);
    m.rotation.x = -Math.PI / 2;
    m.position.set(x, 0.03, z);
    m.scale.set(sx, sz, 1);
    garden.add(m);
  };
  blob(-0.95, 2.95, 2.4, 1.9);
  blob(1.05, 3.35, 2.4, 1.9);
  blob(0.1, 0.4, 5.5, 3.6);

  /* ----- fireflies and petals ----- */
  const glowTex = canvasTex(64, 64, (g) => {
    const gr = g.createRadialGradient(32, 32, 0, 32, 32, 32);
    gr.addColorStop(0, 'rgba(255,244,205,1)');
    gr.addColorStop(0.18, 'rgba(255,220,150,0.7)');
    gr.addColorStop(0.5, 'rgba(255,190,120,0.16)');
    gr.addColorStop(1, 'rgba(255,190,120,0)');
    g.fillStyle = gr;
    g.fillRect(0, 0, 64, 64);
  });
  const FLY = lowPower ? 16 : 34;
  const flyPos = new Float32Array(FLY * 3);
  const flyBase: { x: number; y: number; z: number; ph: number; sp: number }[] = [];
  {
    const rf = rng(3);
    for (let i = 0; i < FLY; i++) flyBase.push({ x: (rf() - 0.5) * 13, y: 0.5 + rf() * 4.2, z: -3 + rf() * 9, ph: rf() * 6.28, sp: 0.2 + rf() * 0.5 });
  }
  const flyGeo = new THREE.BufferGeometry();
  flyGeo.setAttribute('position', new THREE.BufferAttribute(flyPos, 3));
  const flyMat = new THREE.PointsMaterial({ map: glowTex, size: 0.36, transparent: true, depthWrite: false, blending: THREE.AdditiveBlending, sizeAttenuation: true });
  const flies = new THREE.Points(flyGeo, flyMat);
  flies.frustumCulled = false;
  garden.add(flies);

  const PETALS = lowPower ? 12 : 30;
  const petalGeo = new THREE.PlaneGeometry(0.13, 0.15);
  const petalMat = new THREE.MeshBasicMaterial({ map: leafTex, color: 0x9cc4ff, alphaTest: 0.5, side: THREE.DoubleSide });
  const petals = new THREE.InstancedMesh(petalGeo, petalMat, PETALS);
  const petalState: { x: number; y: number; z: number; v: number; ph: number }[] = [];
  {
    const rp = rng(41);
    for (let i = 0; i < PETALS; i++) petalState.push({ x: (rp() - 0.5) * 8, y: rp() * 6, z: -1 + rp() * 5, v: 0.25 + rp() * 0.35, ph: rp() * 6.28 });
  }
  petals.frustumCulled = false;
  garden.add(petals);

  /* ---------- composer (bloom makes the leaves, moon and fireflies glow) ---------- */
  let composer: EffectComposer | null = null;
  let bloom: UnrealBloomPass | null = null;
  const useBloom = !lowPower;
  const buildComposer = () => {
    composer?.dispose();
    composer = null;
    bloom = null;
    if (!useBloom || quality < 0.7) return;
    composer = new EffectComposer(renderer);
    const bgPass = new RenderPass(bgScene, bgCam);
    bgPass.clear = true;
    const garPass = new RenderPass(scene, camera);
    garPass.clear = false;
    garPass.clearDepth = true;
    bloom = new UnrealBloomPass(new THREE.Vector2(W, H), 0.32, 0.55, 0.9);
    composer.addPass(bgPass);
    composer.addPass(garPass);
    composer.addPass(bloom);
    composer.addPass(new OutputPass());
    composer.setPixelRatio(1);
    composer.setSize(W, H);
  };

  /* ---------- layout / camera ---------- */
  const resize = () => {
    const cssW = canvas.clientWidth || window.innerWidth;
    const cssH = canvas.clientHeight || window.innerHeight;
    const dpr = Math.min(window.devicePixelRatio || 1, MAX_DPR) * quality;
    W = Math.max(2, Math.round(cssW * dpr));
    H = Math.max(2, Math.round(cssH * dpr));
    renderer.setPixelRatio(1);
    renderer.setSize(W, H, false);
    aspect = W / H;
    lakeMat.uniforms.uRes.value.set(W, H);
    camera.aspect = aspect;
    if (composer) composer.setSize(W, H);
    else if (useBloom && quality >= 0.7) buildComposer();
    applyCamera();
  };

  function applyCamera() {
    const p = easeInOut(pan);
    if (mobile) {
      camera.fov = 40;
      const endX = GX + 0.2;
      const x = lerp(0, endX, p);
      camera.position.set(x, lerp(2.2, 1.9, p) - scrollPx * 0.0011, lerp(16, 14.5, p));
      camera.lookAt(x, lerp(2.4, 2.8, p) - scrollPx * 0.0009, 0);
      camera.setViewOffset(W, H, 0, Math.round(H * 0.215), W, H); // the scene lives in the top part: shift it up
    } else {
      camera.fov = 34;
      const visH = 2 * 10.2 * Math.tan((34 * Math.PI) / 360);
      const endX = GX + 0.18 * visH * aspect; // puts the trunk at about a third of the screen width, chairs inside the left half
      const x = lerp(0, endX, p);
      camera.position.set(x, lerp(2.0, 1.95, p) - scrollPx * 0.0011, lerp(12.5, 10.4, p));
      camera.lookAt(x, lerp(2.7, 2.15, p) - scrollPx * 0.0009, 0);
      camera.clearViewOffset();
    }
    camera.updateProjectionMatrix();
    lakeMat.uniforms.uCam.value = (p * 1.9) * 1.0;
    lakeMat.uniforms.uMoonX.value = 0.23 * aspect;
  }

  /* ---------- frame ---------- */
  const tmpM = new THREE.Matrix4(), tmpQ = new THREE.Quaternion(), tmpE = new THREE.Euler(), tmpS = new THREE.Vector3(), tmpP = new THREE.Vector3();
  const draw = (now: number) => {
    const t = reduceStill ? 3 : (now - t0) / 1000;
    lakeMat.uniforms.uTime.value = t;
    grassUniforms.uTime.value = t;
    for (let i = 0; i < FLY; i++) {
      const f = flyBase[i];
      const pulse = Math.sin(t * (0.4 + f.sp) + f.ph);
      flyPos[i * 3] = f.x + Math.sin(t * f.sp + f.ph) * 0.9;
      flyPos[i * 3 + 1] = f.y + Math.sin(t * f.sp * 1.3 + f.ph * 2) * 0.5 + pulse * 0.1;
      flyPos[i * 3 + 2] = f.z + Math.cos(t * f.sp * 0.8 + f.ph) * 0.8;
    }
    flyGeo.attributes.position.needsUpdate = true;
    flyMat.opacity = 0.9;
    for (let i = 0; i < PETALS; i++) {
      const s = petalState[i];
      const y = (6 - ((s.y + t * s.v) % 6.4));
      tmpP.set(s.x + Math.sin(t * 0.6 + s.ph) * 0.7, y, s.z + Math.cos(t * 0.5 + s.ph) * 0.4);
      tmpE.set(t * 0.8 + s.ph, t * 0.6 + s.ph * 2, t * 0.7);
      tmpQ.setFromEuler(tmpE);
      tmpS.setScalar(1);
      tmpM.compose(tmpP, tmpQ, tmpS);
      petals.setMatrixAt(i, tmpM);
    }
    petals.instanceMatrix.needsUpdate = true;
    canopyGlow.intensity = 16 + Math.sin(t * 0.6) * 1.5;

    if (composer) {
      composer.render();
    } else {
      renderer.clear();
      renderer.render(bgScene, bgCam);
      renderer.clearDepth();
      renderer.render(scene, camera);
    }
  };

  const minDt = lowPower ? 30 : 15;
  const loop = (now: number) => {
    if (!running || destroyed) return;
    raf = requestAnimationFrame(loop);
    const dt = now - lastT;
    if (dt < minDt) return;
    lastT = now;
    draw(now);
    if (dt > (lowPower ? 60 : 32) && quality > 0.55) {
      if (++slow > 28) {
        slow = 0;
        quality = Math.max(0.55, quality - 0.12);
        if (quality < 0.7 && composer) {
          composer.dispose();
          composer = null;
        }
        resize();
      }
    } else slow = Math.max(0, slow - 1);
  };
  const start = () => {
    if (running || destroyed) return;
    if (reduceStill) {
      if (ready) draw(performance.now());
      return;
    }
    running = true;
    lastT = 0;
    raf = requestAnimationFrame(loop);
  };
  const stop = () => {
    running = false;
    if (raf) cancelAnimationFrame(raf);
    raf = 0;
  };

  /* ---------- optional: replace the generated tree / chair / rocks with downloaded open-licence .glb files ---------- */
  const loadOverrides = async () => {
    const loader = new GLTFLoader();
    const fit = (obj: THREE.Object3D, targetHeight: number) => {
      const box = new THREE.Box3().setFromObject(obj);
      const size = box.getSize(new THREE.Vector3());
      const s = targetHeight / Math.max(0.001, size.y);
      obj.scale.multiplyScalar(s);
      const b2 = new THREE.Box3().setFromObject(obj);
      obj.position.y -= b2.min.y;
      const c = b2.getCenter(new THREE.Vector3());
      obj.position.x -= c.x;
      obj.position.z -= c.z;
      return obj;
    };
    const tryLoad = async (name: string) => {
      try {
        const head = await fetch(MODEL_BASE + name, { method: 'HEAD' });
        if (!head.ok || (head.headers.get('content-type') || '').includes('text/html')) return null;
        return await loader.loadAsync(MODEL_BASE + name);
      } catch {
        return null;
      }
    };
    if (!opts.overrides) return;
    const tree = await tryLoad('tree.glb');
    if (tree && !destroyed) {
      garden.remove(bark, leaves);
      const holder = new THREE.Group();
      holder.add(fit(tree.scene, 8.5));
      garden.add(holder);
    }
    const chair = await tryLoad('chair.glb');
    if (chair && !destroyed) {
      garden.remove(chairs);
      const mk = (x: number, z: number, ry: number) => {
        const g = new THREE.Group();
        const o = chair.scene.clone(true);
        g.add(fit(o, 1.45));
        g.position.set(x, 0, z);
        g.rotation.y = ry;
        return g;
      };
      garden.add(mk(-0.95, 2.9, 0.72), mk(1.05, 3.3, -0.78));
    }
    const rock = await tryLoad('rock.glb');
    if (rock && !destroyed) {
      rockGroup.clear();
      [[-7.5, -9, 3], [-3.8, -12, 2.4], [4.5, -10, 2.8], [8.5, -8, 3.4], [11.5, -11, 2.9]].forEach(([x, z, h], i) => {
        const o = rock.scene.clone(true);
        fit(o, h);
        o.position.add(new THREE.Vector3(x, 0, z));
        o.rotation.y = i * 1.7;
        rockGroup.add(o);
      });
    }
  };

  /* ---------- go ---------- */
  resize();
  buildComposer();
  resize();
  ready = true;
  draw(performance.now());
  setTimeout(() => {
    if (destroyed) return;
    draw(performance.now());
    opts.onReady?.();
    void loadOverrides();
  }, 0);

  const onLost = (e: Event) => {
    e.preventDefault();
    stop();
  };
  canvas.addEventListener('webglcontextlost', onLost);

  return {
    setPan(p: number) {
      pan = Math.max(0, Math.min(1, p));
      applyCamera();
      if (ready && (reduceStill || !running)) draw(performance.now());
    },
    setMobile(m: boolean) {
      if (mobile === m) return;
      mobile = m;
      applyCamera();
    },
    setScroll(px: number) {
      scrollPx = Math.max(0, Math.min(1800, px));
      applyCamera();
      if (ready && (reduceStill || !running)) draw(performance.now());
    },
    start,
    stop,
    resize() {
      resize();
      if (ready) draw(performance.now());
    },
    renderOnce() {
      if (ready) draw(performance.now());
    },
    destroy() {
      destroyed = true;
      stop();
      canvas.removeEventListener('webglcontextlost', onLost);
      composer?.dispose();
      renderer.dispose();
      try {
        renderer.forceContextLoss();
      } catch {
        /* ignore */
      }
    },
  };
}
